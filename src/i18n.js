export const makeT = (lang) => {
  const i = lang === 'vi' ? 0 : 1;
  return {
    ...T[lang],
    lang,
    arch: (n) => ARCH[n]?.[i] ?? String(n),
    skill: (code) => SKILL_NAMES[code]?.[i] ?? code,
    env: (e) => ENV_NAMES[e]?.[i] ?? e,
    sig: (g) => SIGNAL_NAMES[g][i],
    school: (g) => SIGNAL_NAMES[g][2],
    labelName: (l) => LABEL_NAMES[l][i],
    profileName: (pr) => pr.a.map((n) => ARCH[n]?.[i] ?? n).join(' + '),
    persona: (p) => PERSONA_NAMES[p][i],
    num: (x, d = 3) => (lang === 'vi' ? x.toFixed(d).replace('.', ',') : x.toFixed(d)),
  };
};
